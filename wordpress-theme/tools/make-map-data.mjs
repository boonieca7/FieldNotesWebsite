import fs from 'fs';
import { feature } from 'topojson-client';
import { geoConicConformal, geoPath, geoArea } from 'd3-geo';
const topo = JSON.parse(fs.readFileSync('node_modules/world-atlas/countries-110m.json'));
const all = feature(topo, topo.objects.countries).features;
const W = 800, H = 640;
const proj = geoConicConformal().rotate([-15, 0]).center([0, 50]).parallels([40, 60]).scale(1050).translate([W/2, H/2]).clipExtent([[0,0],[W,H]]);
const path = geoPath(proj).digits(1);
const slug = s => s.normalize('NFD').replace(/[̀-ͯ]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'');
const rows = [];
for (const f of all) {
  const d = path(f); if (!d) continue;
  let g = f.geometry, best = g;
  if (g.type === 'MultiPolygon') { let a = -1; for (const p of g.coordinates) { const s = geoArea({type:'Polygon',coordinates:p}); if (s > a) { a = s; best = {type:'Polygon',coordinates:p}; } } }
  const c = geoPath(proj).centroid(best);
  if (!isFinite(c[0]) || c[0] < 0 || c[0] > W || c[1] < 0 || c[1] > H) { rows.push([slug(f.properties.name), f.properties.name, d, -1, -1]); continue; }
  rows.push([slug(f.properties.name), f.properties.name, d, Math.round(c[0]), Math.round(c[1])]);
}
const esc = s => s.replace(/\\/g,'\\\\').replace(/'/g,"\\'");
let php = "<?php\n/**\n * Country outlines for the homepage map: Natural Earth 1:110m, conic projection centred on Europe,\n * 800 x 640. Keys are country names as slugs, so a post category named after a country\n * (Romania -> romania) lights that country up. Generated by the theme's map script.\n */\nif ( ! defined( 'ABSPATH' ) ) { exit; }\n\nfunction fieldnotes_map_countries() {\n\treturn array(\n";
for (const [k,n,d,x,y] of rows) php += `\t\t'${k}' => array( '${esc(n)}', ${x}, ${y}, '${d}' ),\n`;
php += "\t);\n}\n";
fs.writeFileSync('/home/claude/repo/wordpress-theme/field-notes/inc/map-data.php', php);
console.log(rows.length, (php.length/1024).toFixed(0)+'KB', rows.filter(r=>['romania','italy','austria','poland','france','spain','united-kingdom'].includes(r[0])).map(r=>r[0]+':'+r[3]+','+r[4]).join(' '));
